
# Integer 
num = 10

# Float
num_float = 10.5    

# String
name = "Nitish" 

# boolean
is_active = True    

# None
none_var = None


# Print the data types of the variables
print(type(num))
print(type(num_float))
print(type(name))
print(type(is_active))
print(type(none_var))



# Rules for naming variables in Python:
# 1. Variable names can contain letters, numbers, and underscores (_).
# 2. Variable names must start with a letter or an underscore (_).
# 3. Variable names are case-sensitive (e.g., myVar and myvar are different variables).
# 4. Variable names cannot be a reserved keyword in Python (e.g., if, else, while, etc.).
# 5. Variable names should be descriptive and meaningful to enhance code readability.


